//! Shell completion generated from the shared command specification.

use std::fmt::Write as _;

use rune_core::error::{Result, RuneError};

use crate::spec::{self, FlagSpec};

/// Validates the shell selector and renders a script suitable for sourcing.
pub fn render(args: &[String]) -> Result<String> {
    if args.len() != 1 || args.first().map(String::as_str) != Some("bash") {
        return Err(RuneError::invalid_field(
            "shell",
            "expected exactly one supported shell: bash",
        )
        .with_hint("use `rune completion bash`"));
    }
    Ok(render_bash())
}

/// Splits help labels such as `-h, --help` into individual flag spellings.
fn flag_names<'a>(flags: impl Iterator<Item = &'a FlagSpec>, values_only: bool) -> String {
    flags
        .filter(|flag| !values_only || flag.value.is_some())
        .flat_map(|flag| flag.name.split(", "))
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>()
        .join(" ")
}

fn render_bash() -> String {
    let globals = flag_names(spec::GLOBAL_FLAGS.iter(), false);
    let global_values = flag_names(spec::GLOBAL_FLAGS.iter(), true);
    let commands = spec::all_commands()
        .flat_map(|command| {
            std::iter::once(command.name).chain(
                command
                    .aliases
                    .iter()
                    .map(|alias| alias.name)
                    .filter(|name| !name.starts_with('-')),
            )
        })
        .collect::<Vec<_>>()
        .join(" ");
    let mut out = String::from(
        r"# Generated by rune completion bash. Source this file in Bash.
_rune_complete() {
    local cur word command='' expect_value=0 i candidate
    COMPREPLY=()
    cur=${COMP_WORDS[COMP_CWORD]}
",
    );
    let _ = writeln!(out, "    local flags='{globals}'");
    let _ = writeln!(out, "    local value_flags='{global_values}'");
    out.push_str(
        r#"    for ((i=1; i<COMP_CWORD; i++)); do
        word=${COMP_WORDS[i]}
        if ((expect_value)); then
            # Bash may split --flag=value into --flag, =, and value.
            [[ $word == = ]] && continue
            expect_value=0
            continue
        fi
        [[ $word == -- ]] && return 0
        if [[ $word == -* ]]; then
            [[ $word == *=* ]] && continue
            if [[ " $value_flags " == *" $word "* ]]; then
                expect_value=1
            fi
            continue
        fi
        if [[ -z $command ]]; then
            case "$word" in
"#,
    );
    for command in spec::all_commands() {
        let patterns = std::iter::once(command.name)
            .chain(command.aliases.iter().map(|alias| alias.name))
            .collect::<Vec<_>>()
            .join("|");
        let _ = writeln!(out, "                {patterns})");
        let _ = writeln!(out, "                    command='{}'", command.name);
        let _ = writeln!(
            out,
            "                    flags='{}'",
            flag_names(spec::GLOBAL_FLAGS.iter().chain(command.flags.iter()), false)
        );
        let _ = writeln!(
            out,
            "                    value_flags='{}' ;;",
            flag_names(spec::GLOBAL_FLAGS.iter().chain(command.flags.iter()), true)
        );
    }
    out.push_str(
        r"                *) return 0 ;;
            esac
        fi
    done
    ((expect_value)) && return 0
    [[ $cur == --*=* ]] && return 0
",
    );
    let _ = writeln!(out, "    local candidates=\"$flags\"");
    let _ = writeln!(
        out,
        "    [[ -z $command ]] && candidates=\"{commands} $flags\""
    );
    out.push_str(
        r#"    [[ $command == completion && $cur != -* ]] && candidates='bash'
    while IFS= read -r candidate; do
        COMPREPLY+=("$candidate")
    done < <(compgen -W "$candidates" -- "$cur")
    return 0
}
complete -F _rune_complete rune
"#,
    );
    out
}

#[cfg(all(test, unix))]
mod tests {
    use std::io::Write as _;
    use std::process::{Command, Stdio};

    use super::*;

    /// Execute the generated function with Bash's real completion variables.
    fn complete(words: &[&str]) -> Vec<String> {
        let mut child = Command::new("bash")
            .args(["--noprofile", "--norc"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("Bash is required to test Bash completion");
        let mut script = render_bash();
        script.push_str("COMP_WORDS=(");
        for word in words {
            // Quote test words so prompts and option values are literal data.
            let _ = write!(script, " '{}'", word.replace('\'', "'\\''"));
        }
        let _ = writeln!(script, " )\nCOMP_CWORD={}", words.len().saturating_sub(1));
        script.push_str("_rune_complete\nprintf '%s\\n' \"${COMPREPLY[@]}\"\n");
        child
            .stdin
            .take()
            .expect("stdin")
            .write_all(script.as_bytes())
            .expect("write script");
        let output = child.wait_with_output().expect("run script");
        assert!(output.status.success(), "{output:?}");
        assert!(output.stderr.is_empty(), "{output:?}");
        String::from_utf8(output.stdout)
            .expect("utf8")
            .lines()
            .filter(|line| !line.is_empty())
            .map(str::to_owned)
            .collect()
    }

    #[test]
    fn bash_offers_every_declared_command_alias_and_global_flag() {
        let offered = complete(&["rune", ""]);
        for command in spec::all_commands() {
            for name in
                std::iter::once(command.name).chain(command.aliases.iter().map(|alias| alias.name))
            {
                assert!(offered.iter().any(|word| word == name), "missing {name}");
            }
        }
        for flag in spec::GLOBAL_FLAGS {
            for name in flag.name.split(',').map(str::trim) {
                assert!(offered.iter().any(|word| word == name), "missing {name}");
            }
        }
        assert_eq!(complete(&["rune", "res"]), ["resume"]);
    }

    #[test]
    fn bash_offers_every_commands_flags_through_names_and_aliases() {
        for command in spec::all_commands() {
            for name in std::iter::once(command.name)
                .chain(command.aliases.iter().map(|alias| alias.name))
                .filter(|name| !name.starts_with('-'))
            {
                let offered = complete(&["rune", name, "-"]);
                let expected = spec::GLOBAL_FLAGS
                    .iter()
                    .chain(command.flags.iter())
                    .flat_map(|flag| flag.name.split(','))
                    .map(str::trim)
                    .collect::<std::collections::BTreeSet<_>>();
                assert_eq!(
                    offered
                        .iter()
                        .map(String::as_str)
                        .collect::<std::collections::BTreeSet<_>>(),
                    expected,
                    "{name} completion flags"
                );
                assert_eq!(offered.len(), expected.len(), "{name} duplicate flags");
            }
        }
    }

    #[test]
    fn bash_skips_option_values_and_respects_prefixes_and_end_of_flags() {
        for words in [
            vec!["rune", "--model", "ask", "sessions", "--se"],
            vec!["rune", "--model=ask", "sessions", "--se"],
            vec!["rune", "--model", "=", "ask", "sessions", "--se"],
            vec!["rune", "sessions", "--search", "ask", "--se"],
            vec!["rune", "sessions", "--search=ask", "--se"],
            vec!["rune", "sessions", "--search", "=", "ask", "--se"],
        ] {
            assert_eq!(complete(&words), ["--search"]);
        }
        assert_eq!(complete(&["rune", "ask", "--json"]), ["--json", "--jsonl"]);
        for words in [
            vec!["rune", "--model", ""],
            vec!["rune", "sessions", "--search", ""],
            vec!["rune", "ask", "--", "--"],
        ] {
            assert!(complete(&words).is_empty(), "{words:?}");
        }
        assert!(complete(&["rune", "--model=a"]).is_empty());
        assert_eq!(complete(&["rune", "completion", "b"]), ["bash"]);
    }
}
