//! Shell completion generated from the shared command specification.

use std::fmt::Write as _;

use rune_core::error::{Result, RuneError};

use crate::spec::{self, FlagSpec};

/// The shells a completion script is generated for.
const SHELLS: [&str; 4] = ["bash", "zsh", "fish", "powershell"];

/// Validates the shell selector and renders a script suitable for sourcing.
pub fn render(args: &[String]) -> Result<String> {
    match args {
        [shell] if shell == "bash" => Ok(render_bash()),
        [shell] if shell == "zsh" => Ok(render_zsh()),
        [shell] if shell == "fish" => Ok(render_fish()),
        [shell] if shell == "powershell" => Ok(render_powershell()),
        _ => Err(RuneError::invalid_field(
            "shell",
            "expected one supported shell: bash, zsh, fish or powershell",
        )
        .with_hint("use rune completion zsh, for example")),
    }
}

/// A command's names: its own and the aliases that are words.
fn command_names(command: &spec::CommandSpec) -> Vec<&'static str> {
    std::iter::once(command.name)
        .chain(
            command
                .aliases
                .iter()
                .map(|alias| alias.name)
                .filter(|name| !name.starts_with('-')),
        )
        .collect()
}

/// Each spelling of a flag, as `-h` and `--help` for `-h, --help`.
fn spellings(flag: &FlagSpec) -> impl Iterator<Item = &'static str> {
    flag.name.split(", ").map(str::trim)
}

/// Quotes `text` for a single-quoted zsh or fish word.
fn quote_posix(text: &str) -> String {
    format!("'{}'", text.replace('\'', "'\\''"))
}

/// Quotes `text` for a single-quoted PowerShell string.
fn quote_powershell(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

/// One `_arguments` entry for a flag spelling: its description in brackets
/// and, for a flag that takes a value, the value's name.
fn zsh_flag(spelling: &str, flag: &FlagSpec) -> String {
    let description = flag
        .description
        .replace('\\', "\\\\")
        .replace('[', "\\[")
        .replace(']', "\\]");
    let value = flag
        .value
        .map(|value| format!(":{}: ", value.replace(':', "\\:")))
        .unwrap_or_default();
    quote_posix(&format!("{spelling}[{description}]{value}"))
}

fn render_zsh() -> String {
    let mut out = String::from("#compdef rune\n# Generated by rune completion zsh.\n_rune() {\n");
    out.push_str("    local -a commands globals\n    commands=(\n");
    for command in spec::all_commands() {
        for name in command_names(command) {
            let entry = format!("{}:{}", name.replace(':', "\\:"), command.summary);
            let _ = writeln!(out, "        {}", quote_posix(&entry));
        }
    }
    out.push_str("    )\n    globals=(\n");
    for flag in spec::GLOBAL_FLAGS {
        for spelling in spellings(flag) {
            let _ = writeln!(out, "        {}", zsh_flag(spelling, flag));
        }
    }
    out.push_str(
        "    )\n    local state\n    _arguments -C $globals '1: :->command' '*:: :->args'\n    case $state in\n        command) _describe command commands ;;\n        args)\n            case $words[1] in\n",
    );
    for command in spec::all_commands() {
        let _ = write!(
            out,
            "                {}) _arguments $globals",
            command_names(command).join("|")
        );
        for flag in command.flags {
            for spelling in spellings(flag) {
                let _ = write!(out, " {}", zsh_flag(spelling, flag));
            }
        }
        if command.name == "completion" {
            let _ = write!(out, " '1:shell:({})'", SHELLS.join(" "));
        }
        out.push_str(" ;;\n");
    }
    out.push_str(
        "            esac ;;\n    esac\n}\nif (( $+functions[compdef] )); then\n    compdef _rune rune\nfi\n",
    );
    out
}

/// One `complete` line for a flag, with `condition` when it belongs to a command.
fn fish_flag(flag: &FlagSpec, condition: Option<&str>) -> String {
    let mut line = String::from("complete -c rune");
    if let Some(condition) = condition {
        let _ = write!(line, " -n {}", quote_posix(condition));
    }
    for spelling in spellings(flag) {
        match spelling.strip_prefix("--") {
            Some(long) => {
                let _ = write!(line, " -l {long}");
            }
            None => {
                let _ = write!(line, " -s {}", spelling.trim_start_matches('-'));
            }
        }
    }
    if flag.value.is_some() {
        line.push_str(" -r");
    }
    let _ = write!(line, " -d {}", quote_posix(flag.description));
    line
}

fn render_fish() -> String {
    let mut out = String::from("# Generated by rune completion fish.\ncomplete -c rune -f\n");
    for command in spec::all_commands() {
        for name in command_names(command) {
            let _ = writeln!(
                out,
                "complete -c rune -n __fish_use_subcommand -a {} -d {}",
                quote_posix(name),
                quote_posix(command.summary)
            );
        }
    }
    for flag in spec::GLOBAL_FLAGS {
        let _ = writeln!(out, "{}", fish_flag(flag, None));
    }
    for command in spec::all_commands() {
        let condition = format!(
            "__fish_seen_subcommand_from {}",
            command_names(command).join(" ")
        );
        for flag in command.flags {
            let _ = writeln!(out, "{}", fish_flag(flag, Some(&condition)));
        }
        if command.name == "completion" {
            let _ = writeln!(
                out,
                "complete -c rune -n {} -a {}",
                quote_posix(&condition),
                quote_posix(&SHELLS.join(" "))
            );
        }
    }
    out
}

fn render_powershell() -> String {
    let list = |items: &mut dyn Iterator<Item = &str>| {
        items.map(quote_powershell).collect::<Vec<_>>().join(", ")
    };
    let mut out = String::from(
        "# Generated by rune completion powershell.\nRegister-ArgumentCompleter -Native -CommandName rune -ScriptBlock {\n    param($wordToComplete, $commandAst, $cursorPosition)\n    $commands = [ordered]@{\n",
    );
    for command in spec::all_commands() {
        for name in command_names(command) {
            let _ = writeln!(
                out,
                "        {} = {}",
                quote_powershell(name),
                quote_powershell(command.summary)
            );
        }
    }
    let globals = spec::GLOBAL_FLAGS
        .iter()
        .flat_map(spellings)
        .collect::<Vec<_>>();
    let global_values = spec::GLOBAL_FLAGS
        .iter()
        .filter(|flag| flag.value.is_some())
        .flat_map(spellings)
        .collect::<Vec<_>>();
    let _ = writeln!(
        out,
        "    }}\n    $globals = @({})\n    $values = @({})\n    $flags = @{{",
        list(&mut globals.iter().copied()),
        list(&mut global_values.iter().copied())
    );
    for command in spec::all_commands() {
        let own = command.flags.iter().flat_map(spellings).collect::<Vec<_>>();
        let valued = command
            .flags
            .iter()
            .filter(|flag| flag.value.is_some())
            .flat_map(spellings)
            .collect::<Vec<_>>();
        let extra = if command.name == "completion" {
            SHELLS.to_vec()
        } else {
            Vec::new()
        };
        for name in command_names(command) {
            let _ = writeln!(
                out,
                "        {} = @(@({}), @({}), @({}))",
                quote_powershell(name),
                list(&mut own.iter().copied()),
                list(&mut valued.iter().copied()),
                list(&mut extra.iter().copied())
            );
        }
    }
    out.push_str(
        r#"    }
    $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })
    if ($wordToComplete -ne '' -and $words.Count -gt 0) {
        $words = @($words | Select-Object -SkipLast 1)
    }
    $command = $null
    $expectValue = $false
    foreach ($word in $words) {
        if ($expectValue) { $expectValue = $false; continue }
        if ($word -like '-*') {
            $valued = $values
            if ($command) { $valued = $values + $flags[$command][1] }
            if ($valued -contains $word) { $expectValue = $true }
            continue
        }
        if (-not $command) { $command = $word }
    }
    if ($expectValue) { return }
    $candidates = @()
    if (-not $command) {
        if ($wordToComplete -notlike '-*') {
            foreach ($name in $commands.Keys) {
                $candidates += [System.Management.Automation.CompletionResult]::new($name, $name, 'ParameterValue', $commands[$name])
            }
        }
        $names = $globals
    } elseif ($flags.Contains($command)) {
        $names = $globals + $flags[$command][0]
        if ($wordToComplete -notlike '-*') {
            foreach ($name in $flags[$command][2]) {
                $candidates += [System.Management.Automation.CompletionResult]::new($name, $name, 'ParameterValue', $name)
            }
        }
    } else {
        $names = $globals
    }
    foreach ($name in $names) {
        $candidates += [System.Management.Automation.CompletionResult]::new($name, $name, 'ParameterName', $name)
    }
    $candidates | Where-Object { $_.CompletionText -like "$wordToComplete*" }
}
"#,
    );
    out
}

/// Splits help labels such as `-h, --help` into individual flag spellings.
fn flag_names<'a>(flags: impl Iterator<Item = &'a FlagSpec>, values_only: bool) -> String {
    flags
        .filter(|flag| !values_only || flag.value.is_some())
        .flat_map(|flag| flag.name.split(", "))
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>()
        .join(" ")
}

fn render_bash() -> String {
    let globals = flag_names(spec::GLOBAL_FLAGS.iter(), false);
    let global_values = flag_names(spec::GLOBAL_FLAGS.iter(), true);
    let commands = spec::all_commands()
        .flat_map(|command| {
            std::iter::once(command.name).chain(
                command
                    .aliases
                    .iter()
                    .map(|alias| alias.name)
                    .filter(|name| !name.starts_with('-')),
            )
        })
        .collect::<Vec<_>>()
        .join(" ");
    let mut out = String::from(
        r"# Generated by rune completion bash. Source this file in Bash.
_rune_complete() {
    local cur word command='' expect_value=0 i candidate
    COMPREPLY=()
    cur=${COMP_WORDS[COMP_CWORD]}
",
    );
    let _ = writeln!(out, "    local flags='{globals}'");
    let _ = writeln!(out, "    local value_flags='{global_values}'");
    out.push_str(
        r#"    for ((i=1; i<COMP_CWORD; i++)); do
        word=${COMP_WORDS[i]}
        if ((expect_value)); then
            # Bash may split --flag=value into --flag, =, and value.
            [[ $word == = ]] && continue
            expect_value=0
            continue
        fi
        [[ $word == -- ]] && return 0
        if [[ $word == -* ]]; then
            [[ $word == *=* ]] && continue
            if [[ " $value_flags " == *" $word "* ]]; then
                expect_value=1
            fi
            continue
        fi
        if [[ -z $command ]]; then
            case "$word" in
"#,
    );
    for command in spec::all_commands() {
        let patterns = std::iter::once(command.name)
            .chain(command.aliases.iter().map(|alias| alias.name))
            .collect::<Vec<_>>()
            .join("|");
        let _ = writeln!(out, "                {patterns})");
        let _ = writeln!(out, "                    command='{}'", command.name);
        let _ = writeln!(
            out,
            "                    flags='{}'",
            flag_names(spec::GLOBAL_FLAGS.iter().chain(command.flags.iter()), false)
        );
        let _ = writeln!(
            out,
            "                    value_flags='{}' ;;",
            flag_names(spec::GLOBAL_FLAGS.iter().chain(command.flags.iter()), true)
        );
    }
    out.push_str(
        r"                *) return 0 ;;
            esac
        fi
    done
    ((expect_value)) && return 0
    [[ $cur == --*=* ]] && return 0
",
    );
    let _ = writeln!(out, "    local candidates=\"$flags\"");
    let _ = writeln!(
        out,
        "    [[ -z $command ]] && candidates=\"{commands} $flags\""
    );
    out.push_str(
        r#"    [[ $command == completion && $cur != -* ]] && candidates='bash zsh fish powershell'
    while IFS= read -r candidate; do
        COMPREPLY+=("$candidate")
    done < <(compgen -W "$candidates" -- "$cur")
    return 0
}
complete -F _rune_complete rune
"#,
    );
    out
}

#[cfg(all(test, unix))]
mod tests {
    use std::io::Write as _;
    use std::process::{Command, Stdio};

    use super::*;

    /// Execute the generated function with Bash's real completion variables.
    fn complete(words: &[&str]) -> Vec<String> {
        let mut child = Command::new("bash")
            .args(["--noprofile", "--norc"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("Bash is required to test Bash completion");
        let mut script = render_bash();
        script.push_str("COMP_WORDS=(");
        for word in words {
            // Quote test words so prompts and option values are literal data.
            let _ = write!(script, " '{}'", word.replace('\'', "'\\''"));
        }
        let _ = writeln!(script, " )\nCOMP_CWORD={}", words.len().saturating_sub(1));
        script.push_str("_rune_complete\nprintf '%s\\n' \"${COMPREPLY[@]}\"\n");
        child
            .stdin
            .take()
            .expect("stdin")
            .write_all(script.as_bytes())
            .expect("write script");
        let output = child.wait_with_output().expect("run script");
        assert!(output.status.success(), "{output:?}");
        assert!(output.stderr.is_empty(), "{output:?}");
        String::from_utf8(output.stdout)
            .expect("utf8")
            .lines()
            .filter(|line| !line.is_empty())
            .map(str::to_owned)
            .collect()
    }

    #[test]
    fn bash_offers_every_declared_command_alias_and_global_flag() {
        let offered = complete(&["rune", ""]);
        for command in spec::all_commands() {
            for name in
                std::iter::once(command.name).chain(command.aliases.iter().map(|alias| alias.name))
            {
                assert!(offered.iter().any(|word| word == name), "missing {name}");
            }
        }
        for flag in spec::GLOBAL_FLAGS {
            for name in flag.name.split(',').map(str::trim) {
                assert!(offered.iter().any(|word| word == name), "missing {name}");
            }
        }
        assert_eq!(complete(&["rune", "res"]), ["resume"]);
    }

    #[test]
    fn bash_offers_every_commands_flags_through_names_and_aliases() {
        for command in spec::all_commands() {
            for name in std::iter::once(command.name)
                .chain(command.aliases.iter().map(|alias| alias.name))
                .filter(|name| !name.starts_with('-'))
            {
                let offered = complete(&["rune", name, "-"]);
                let expected = spec::GLOBAL_FLAGS
                    .iter()
                    .chain(command.flags.iter())
                    .flat_map(|flag| flag.name.split(','))
                    .map(str::trim)
                    .collect::<std::collections::BTreeSet<_>>();
                assert_eq!(
                    offered
                        .iter()
                        .map(String::as_str)
                        .collect::<std::collections::BTreeSet<_>>(),
                    expected,
                    "{name} completion flags"
                );
                assert_eq!(offered.len(), expected.len(), "{name} duplicate flags");
            }
        }
    }

    #[test]
    fn bash_skips_option_values_and_respects_prefixes_and_end_of_flags() {
        for words in [
            vec!["rune", "--model", "ask", "sessions", "--se"],
            vec!["rune", "--model=ask", "sessions", "--se"],
            vec!["rune", "--model", "=", "ask", "sessions", "--se"],
            vec!["rune", "sessions", "--search", "ask", "--se"],
            vec!["rune", "sessions", "--search=ask", "--se"],
            vec!["rune", "sessions", "--search", "=", "ask", "--se"],
        ] {
            assert_eq!(complete(&words), ["--search"]);
        }
        assert_eq!(complete(&["rune", "ask", "--json"]), ["--json", "--jsonl"]);
        for words in [
            vec!["rune", "--model", ""],
            vec!["rune", "sessions", "--search", ""],
            vec!["rune", "ask", "--", "--"],
        ] {
            assert!(complete(&words).is_empty(), "{words:?}");
        }
        assert!(complete(&["rune", "--model=a"]).is_empty());
        assert_eq!(complete(&["rune", "completion", "b"]), ["bash"]);
    }

    /// Every command name, alias and global flag spelling, as each script must name it.
    fn expected_words() -> Vec<String> {
        let mut words: Vec<String> = spec::all_commands()
            .flat_map(command_names)
            .map(str::to_owned)
            .collect();
        words.extend(
            spec::GLOBAL_FLAGS
                .iter()
                .flat_map(spellings)
                .map(str::to_owned),
        );
        words
    }

    fn assert_lists_everything(script: &str, word: impl Fn(&str) -> String) {
        for expected in expected_words() {
            assert!(script.contains(&word(&expected)), "missing {expected}");
        }
    }

    #[test]
    fn zsh_lists_every_command_and_global_flag() {
        let script = render(&["zsh".to_owned()]).expect("zsh");
        assert!(script.starts_with("#compdef rune\n"));
        assert!(script.contains("compdef _rune rune"));
        assert_lists_everything(&script, |word| {
            if word.starts_with('-') {
                format!("'{word}[")
            } else {
                format!("'{word}:")
            }
        });
    }

    #[test]
    fn fish_lists_every_command_and_global_flag() {
        let script = render(&["fish".to_owned()]).expect("fish");
        assert_lists_everything(&script, |word| match word.strip_prefix("--") {
            Some(long) => format!(" -l {long}"),
            None if word.starts_with('-') => format!(" -s {}", word.trim_start_matches('-')),
            None => format!("-a '{word}'"),
        });
    }

    #[test]
    fn powershell_lists_every_command_and_global_flag() {
        let script = render(&["powershell".to_owned()]).expect("powershell");
        assert!(script.contains("Register-ArgumentCompleter -Native -CommandName rune"));
        assert_lists_everything(&script, |word| format!("'{word}'"));
    }

    #[test]
    fn an_unknown_shell_names_the_supported_ones() {
        let error = render(&["tcsh".to_owned()]).expect_err("refused");
        assert_eq!(
            error.message(),
            "expected one supported shell: bash, zsh, fish or powershell"
        );
        assert_eq!(error.hint(), Some("use rune completion zsh, for example"));
    }

    /// Runs `program` with `arguments` and the script's path, when it is installed.
    fn parses(program: &str, arguments: &[&str], shell: &str) {
        let script = render(&[shell.to_owned()]).expect("script");
        let dir = tempfile::tempdir().expect("tempdir");
        let path = dir.path().join(format!("rune.{shell}"));
        std::fs::write(&path, script).expect("script file");
        let Ok(output) = Command::new(program)
            .args(arguments)
            .arg(&path)
            .stdin(Stdio::null())
            .output()
        else {
            eprintln!("skipped: {program} is not installed");
            return;
        };
        assert!(
            output.status.success(),
            "{program} refused the {shell} script: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    #[test]
    fn zsh_script_parses() {
        parses("zsh", &["-n"], "zsh");
    }

    #[test]
    fn fish_script_parses() {
        parses("fish", &["--no-execute"], "fish");
    }

    #[test]
    fn powershell_script_parses() {
        let script = render(&["powershell".to_owned()]).expect("script");
        let dir = tempfile::tempdir().expect("tempdir");
        let path = dir.path().join("rune.ps1");
        std::fs::write(&path, script).expect("script file");
        let check = format!(
            "[void][scriptblock]::Create((Get-Content -Raw '{}'))",
            path.display()
        );
        let Ok(output) = Command::new("pwsh")
            .args(["-NoProfile", "-NonInteractive", "-Command", &check])
            .output()
        else {
            eprintln!("skipped: pwsh is not installed");
            return;
        };
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    #[test]
    fn summaries_with_quotes_are_escaped() {
        assert_eq!(quote_posix("it's"), "'it'\\''s'");
        assert_eq!(quote_powershell("it's"), "'it''s'");
        let flag = FlagSpec {
            name: "--mode",
            value: Some("a:b"),
            description: "pick [one] of 'two'",
        };
        assert_eq!(
            zsh_flag("--mode", &flag),
            "'--mode[pick \\[one\\] of '\\''two'\\'']:a\\:b: '"
        );
    }
}
